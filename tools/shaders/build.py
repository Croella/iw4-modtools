"""Compiles tools/shaders/*.hlsl (vsMain/psMain) to vs_3_0/ps_3_0 with the system d3dcompiler_47
and writes src/zone/effectshaders.h. Run with: python tools/shaders/build.py"""
import ctypes, os, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
comp = ctypes.WinDLL('d3dcompiler_47')

def blob_bytes(p):
    vt = ctypes.cast(ctypes.cast(p, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
    gp = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vt[3])
    gs = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vt[4])
    return ctypes.string_at(gp(p), gs(p))

def compile_(src, name, entry, target):
    code, errs = ctypes.c_void_p(), ctypes.c_void_p()
    data = src.encode()
    hr = comp.D3DCompile(ctypes.c_char_p(data), ctypes.c_size_t(len(data)), ctypes.c_char_p(name.encode()), None, None,
                         ctypes.c_char_p(entry.encode()), ctypes.c_char_p(target.encode()),
                         ctypes.c_uint(1 << 15),  # D3DCOMPILE_OPTIMIZATION_LEVEL3
                         ctypes.c_uint(0), ctypes.byref(code), ctypes.byref(errs))
    if hr != 0:
        sys.exit(name + ' ' + entry + ': ' + (blob_bytes(errs).decode(errors='replace') if errs.value else hex(hr & 0xffffffff)))
    return blob_bytes(code)

out = ['// Generated by tools/shaders/build.py from tools/shaders/*.hlsl. Do not edit.', '#pragma once',
       '#include <cstdint>', '', 'namespace effectshaders {', '']
for fn in sorted(os.listdir(here)):
    if not fn.endswith('.hlsl'): continue
    base = fn[:-5]
    src = open(os.path.join(here, fn)).read()
    for entry, target, suffix in (('vsMain', 'vs_3_0', 'vs'), ('psMain', 'ps_3_0', 'ps')):
        code = compile_(src, fn, entry, target)
        assert len(code) % 4 == 0
        ident = base + '_' + suffix
        out.append('// %s %s: %d bytes' % (fn, target, len(code)))
        out.append('inline constexpr uint8_t %s[] = {' % ident)
        for i in range(0, len(code), 16):
            out.append('    ' + ', '.join('0x%02x' % b for b in code[i:i + 16]) + ',')
        out.append('};')
        out.append('')
        print(ident, len(code), 'bytes')
out.append('}  // namespace effectshaders')
open(os.path.join(root, 'src', 'zone', 'effectshaders.h'), 'w').write('\n'.join(out) + '\n')
