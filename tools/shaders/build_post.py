"""Compiles tools/shaders/post/*.hlsl for iw4r_mapload.dll's post passes: every function named
vs* -> vs_3_0, ps* -> ps_3_0, written to src/dll/postshaders.h.
Run with: python tools/shaders/build_post.py"""
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
import ctypes
comp = ctypes.WinDLL('d3dcompiler_47')

def blob_bytes(p):
    vt = ctypes.cast(ctypes.cast(p, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
    gp = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vt[3])
    gs = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vt[4])
    return ctypes.string_at(gp(p), gs(p))

def compile_(src, name, entry, target):
    code, errs = ctypes.c_void_p(), ctypes.c_void_p()
    data = src.encode()
    hr = comp.D3DCompile(ctypes.c_char_p(data), ctypes.c_size_t(len(data)), ctypes.c_char_p(name.encode()), None, None,
                         ctypes.c_char_p(entry.encode()), ctypes.c_char_p(target.encode()),
                         ctypes.c_uint(1 << 15), ctypes.c_uint(0), ctypes.byref(code), ctypes.byref(errs))
    if hr != 0:
        sys.exit(name + ' ' + entry + ': ' + (blob_bytes(errs).decode(errors='replace') if errs.value else hex(hr & 0xffffffff)))
    return blob_bytes(code)

out = ['// Generated by tools/shaders/build_post.py from tools/shaders/post/*.hlsl. Do not edit.', '#pragma once',
       '#include <cstdint>', '', 'namespace postshaders {', '']
pdir = os.path.join(here, 'post')
for fn in sorted(os.listdir(pdir)):
    if not fn.endswith('.hlsl'): continue
    base = fn[:-5]
    src = open(os.path.join(pdir, fn)).read()
    for entry in re.findall(r'^\w+\s+((?:vs|ps)[A-Z]\w*)\s*\(', src, re.M):
        target = entry[:2] + '_3_0'
        code = compile_(src, fn, entry, target)
        ident = base + '_' + entry
        out.append('// %s %s %s: %d bytes' % (fn, entry, target, len(code)))
        out.append('inline constexpr uint8_t %s[] = {' % ident)
        for i in range(0, len(code), 16):
            out.append('    ' + ', '.join('0x%02x' % b for b in code[i:i + 16]) + ',')
        out.append('};')
        out.append('')
        print(ident, len(code), 'bytes')
out.append('}  // namespace postshaders')
open(os.path.join(root, 'src', 'dll', 'postshaders.h'), 'w').write('\n'.join(out) + '\n')
